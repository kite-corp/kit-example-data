#!/usr/bin/env python3
"""Write db/seed.sql deterministically from tools/seed_data.py."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from seed_data import (
    APPOINTMENTS,
    BOOKED_SLOT_IDS,
    DENTISTS,
    LOYALTY_CARDS,
    MENU_ITEMS,
    ORDER_ITEMS,
    ORDERS,
    PATIENTS,
    SLOTS,
    STOCK,
    TREATMENTS,
)

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "db" / "seed.sql"


def _sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def _sql_bool(value: bool) -> str:
    return "true" if value else "false"


def _insert(table: str, columns: list[str], rows: list[dict]) -> str:
    if not rows:
        return ""
    col_list = ", ".join(columns)
    lines: list[str] = [f"INSERT INTO {table} ({col_list}) VALUES"]
    value_lines: list[str] = []
    for row in rows:
        vals = ", ".join(_format_col(row[c], c) for c in columns)
        value_lines.append(f"  ({vals})")
    lines.append(",\n".join(value_lines) + ";")
    return "\n".join(lines)


def _format_col(value: object, col: str) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return _sql_bool(value)
    if isinstance(value, int):
        return str(value)
    return _sql_str(str(value))


def render_seed() -> str:
    parts: list[str] = [
        "-- Generated by tools/build_seed.py. Do not edit by hand.",
        "",
    ]

    menu_rows = sorted(MENU_ITEMS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "cafe.menu_items",
            ["id", "name", "category", "price_cents", "vegan", "gluten_free"],
            menu_rows,
        )
    )
    parts.append("")

    stock_rows = sorted(STOCK, key=lambda r: (r["day"], r["item_id"]))
    parts.append(
        _insert(
            "cafe.stock",
            ["item_id", "day", "left_count"],
            stock_rows,
        )
    )
    parts.append("")

    loyalty_rows = sorted(LOYALTY_CARDS, key=lambda r: r["member_id"])
    parts.append(
        _insert(
            "cafe.loyalty_cards",
            ["member_id", "stamps"],
            loyalty_rows,
        )
    )
    parts.append("")

    order_rows = sorted(ORDERS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "cafe.orders",
            ["id", "member_id", "status", "placed_at", "total_cents"],
            order_rows,
        )
    )
    parts.append("")

    item_rows = sorted(
        ORDER_ITEMS, key=lambda r: (r["order_id"], r["line"])
    )
    parts.append(
        _insert(
            "cafe.order_items",
            ["order_id", "line", "item_id", "milk", "size", "qty", "price_cents"],
            item_rows,
        )
    )
    parts.append("")

    dentist_rows = sorted(DENTISTS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "clinic.dentists",
            ["id", "name", "role"],
            dentist_rows,
        )
    )
    parts.append("")

    treatment_rows = sorted(TREATMENTS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "clinic.treatments",
            ["id", "name", "price_cents", "from_price", "minutes"],
            treatment_rows,
        )
    )
    parts.append("")

    patient_rows = sorted(PATIENTS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "clinic.patients",
            ["id", "name", "phone"],
            patient_rows,
        )
    )
    parts.append("")

    slot_rows: list[dict] = []
    for slot in sorted(SLOTS, key=lambda r: r["id"]):
        slot_rows.append(
            {
                **slot,
                "free": slot["id"] not in BOOKED_SLOT_IDS,
            }
        )
    parts.append(
        _insert(
            "clinic.slots",
            ["id", "starts_at", "minutes", "chair", "dentist_id", "free"],
            slot_rows,
        )
    )
    parts.append("")

    appt_rows = sorted(APPOINTMENTS, key=lambda r: r["id"])
    parts.append(
        _insert(
            "clinic.appointments",
            ["id", "slot_id", "patient_id", "treatment_id", "state"],
            appt_rows,
        )
    )
    parts.append("")

    return "\n".join(parts)


def main() -> None:
    content = render_seed()
    OUT.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
